import assert from 'node:assert/strict';
import fs from 'node:fs';
const read = path => fs.readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const srv = read('lib/cms-media-server.js');
const ui = read('components/admin/CmsApp.jsx');
const sign = read('app/api/admin/media/sign/route.js');
const targets = read('lib/cms-upload-url.mjs');
const direct = read('app/api/admin/media/upload/route.js');
const complete = read('app/api/admin/media/complete/route.js');
const cors = JSON.parse(read('storage-cors.json'));
assert.match(srv, /MAX_BYTES = MAX_MEDIA_BYTES/);
assert.match(srv, /mediaUploadError\(\{name, type, size\}\)/);
assert.match(ui, /mediaUploadError\(\{name:file\.name,type:file\.type,size:file\.size\},type\)/);
assert.match(ui, /MAX_MEDIA_MB/);
assert.match(ui, /Maximum upload: \{MAX_MEDIA_MB\} MB per file/);
assert.match(ui, /For faster website loading:/);
assert.match(ui, /mediaRequest\('sign'/);
assert.match(ui, /method:'PUT'/);
assert.match(ui, /mediaRequest\('complete'/);
assert.match(ui, /file\.size<=DIRECT_UPLOAD_BYTES/);
assert.match(direct, /DIRECT_MAX_BYTES/);
assert.match(targets, /30 \* 60 \* 1000/);
assert.match(targets, /createResumableUpload/);
assert.match(sign, /40\*60\*1000/);
assert.match(complete, /Number\(info\.size\)!==job\.size/);
assert.ok(cors[0].origin.includes('https://shanerynwebsite.vercel.app'));
assert.ok(cors[0].method.includes('PUT'));
console.log('PASS: 100 MB media upload and direct Storage flow configuration');
