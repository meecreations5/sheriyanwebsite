import assert from 'node:assert/strict';
import {normalizeProductDetails} from '../lib/product-details.mjs';
import {read,renderInfo,mockDom} from './look-info-mock.mjs';
assert.deepEqual(normalizeProductDetails(null),{fabric:[],design:[],embroidery:'',occasions:[]});
assert.deepEqual(normalizeProductDetails({fabric:[{},null,{garment:'',description:' '}]}),{fabric:[],design:[],embroidery:'',occasions:[]});
const input={fabric:[{garment:'Black Palazzo Pant',description:'Heavy-weight stretch crepe'},{garment:'<script>alert(1)</script>',description:'text <b>tag</b>'}],design:[{garment:'Top',description:'Silk'}],embroidery:'Beads\nCrystal',occasions:['Gala Dinners','Gala Dinners','Cocktail Parties']};
const normalized=normalizeProductDetails(input);
assert.equal(normalized.fabric.length,2);
assert.deepEqual(normalized.occasions,['Gala Dinners','Cocktail Parties']);
const product={id:'SH-URASHIMA',title:'Urashima Taro',cat:'Pant Sets',tagline:'',description:'Some legacy text',price:'₹18,500',productDetails:input};
let dom=mockDom();renderInfo(dom.$,{slug:'look'},[product],product.id);
const detail=dom.events.find(e=>e.type==='before'&&e.selector==='.ld-actions');
assert.ok(detail,'Product description should be inserted ahead of purchase controls');
for(const label of ['FABRIC','DESIGN DESCRIPTION','EMBROIDERY &amp; DETAILING','OCCASION'])assert.ok(detail.value.includes(label),label);
assert.match(detail.value,/&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
assert.doesNotMatch(detail.value,/<script>|<b>tag<\/b>/);
assert.ok(dom.events.some(e=>e.type==='remove'&&e.selector==='#detail-description'));
const price=dom.events.find(e=>e.type==='after'&&e.selector==='.ld-title-wrap');assert.match(price.value,/₹18,500/);
dom=mockDom();renderInfo(dom.$,{slug:'look'},[{...product,productDetails:null,price:'',description:'Legacy description'}],product.id);
assert.ok(!dom.events.some(e=>e.type==='before'&&e.selector==='.ld-actions'));
assert.ok(!dom.events.some(e=>e.type==='remove'&&e.selector==='#detail-description'));
dom=mockDom();renderInfo(dom.$,{slug:'look'},[{...product,description:'',productDetails:null,price:''}],product.id);
assert.ok(dom.events.some(e=>e.type==='remove'&&e.selector==='#detail-description'));
dom=mockDom();renderInfo(dom.$,{slug:'home'},[product],product.id);
assert.equal(dom.events.length,0);
const api=read('lib/cms-server-api.js'),admin=read('components/admin/CmsApp.jsx');
assert.match(api,/productDetails:normalizeProductDetails\(p\.productDetails\)/);
assert.match(admin,/\+ Add garment/);
assert.match(admin,/\+ Add occasion/);
console.log('PASS V1.18.6: optional descriptions, safe escaping, blank suppression and CMS form preservation');
