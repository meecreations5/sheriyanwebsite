import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const seo=read('lib/seo-utils.js');
const sitemap=read('app/sitemap.js');
const robots=read('app/robots.js');
const layout=read('app/layout.js');
const pages=['app/page.js','app/[slug]/page.js','app/look/[productSlug]/page.js','app/collections/[collectionSlug]/page.js'];
assert.match(seo,/NEXT_PUBLIC_SITE_URL/);
assert.match(seo,/alternates:\s*\{canonical\}/);
assert.match(seo,/openGraph:/);
assert.match(seo,/twitter:/);
assert.match(seo,/robots:/);
assert.match(layout,/metadataBase/);
assert.match(sitemap,/loadPublicPageSlugs/);
assert.match(sitemap,/productPath/);
assert.match(sitemap,/loadCuratedCollections/);
assert.match(sitemap,/page\.visible === false/);
assert.match(robots,/\/admin/);
assert.match(robots,/\/api\//);
for(const page of pages){assert.match(read(page),/buildPublicMetadata/,page)}
assert.match(read('app/admin/page.js'),/noindex,nofollow/);
assert.match(read('lib/cms-data.js'),/loadPublicPageSlugs/);
assert.doesNotMatch(read('lib/cms-login-guard.js'),/ensureInitialAdmin/);
assert.doesNotMatch(seo,/cms_users|cms_internal|passwordHash/);
// Exercise the pure metadata helpers with representative editor data.
const {publicSiteOrigin, publicMediaPath, buildPublicMetadata} = await import('../lib/seo-utils.js');
const originalOrigin = process.env.NEXT_PUBLIC_SITE_URL;
process.env.NEXT_PUBLIC_SITE_URL = 'https://www.example.org/path/';
assert.equal(publicSiteOrigin(),'https://www.example.org');
process.env.NEXT_PUBLIC_SITE_URL = 'javascript:bad';
assert.equal(publicSiteOrigin(),'');
if (originalOrigin===undefined) delete process.env.NEXT_PUBLIC_SITE_URL;
else process.env.NEXT_PUBLIC_SITE_URL=originalOrigin;
assert.equal(publicMediaPath('assets/editorial.jpg'),'/assets/editorial.jpg');
assert.equal(publicMediaPath('javascript:alert(1)'),'');
const meta=buildPublicMetadata({title:'Starlight | SHANERYN',description:'Editorial look.',canonical:'/look/starlight',image:'assets/starlight.jpg',settings:{seo:{siteName:'SHANERYN'},branding:{favicon:'favicon.png'}}});
assert.deepEqual(meta.title,{absolute:'Starlight | SHANERYN'});
assert.equal(meta.alternates.canonical,'/look/starlight');
assert.equal(meta.openGraph.images[0],'/assets/starlight.jpg');
assert.equal(meta.twitter.card,'summary_large_image');
assert.equal(meta.robots.index,true);
assert.equal(buildPublicMetadata({title:'Hidden',canonical:'/secret',index:false}).robots.index,false);
assert.match(sitemap,/product\.collectionIds/);
assert.match(read('app/collections/[collectionSlug]/page.js'),/product\.collectionIds/);
console.log('PASS: V1.18 SEO metadata, canonicals, sitemap, robots and admin isolation checks');
