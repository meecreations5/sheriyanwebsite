import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {collectionType,accessoryPath,accessoryCollectionPath,accessoryCategoryPath,
 accessoryMatchesCollection,visibleAccessories,decorateLookAccessories,legacyAccessories} from '../lib/catalogue-model.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const templates=JSON.parse(read('data/seed/curated-collections.json'));
assert.equal(templates.length,2);
assert.deepEqual(templates.map(c=>c.id),['the-curve-edit','the-curve-edit-adorned']);
assert.ok(templates.every(c=>c.type==='clothing'&&c.visible===false),'starter collections require approval and assignments');
assert.equal(collectionType({id:'legacy'}),'clothing');
assert.equal(collectionType({type:'accessories'}),'accessories');
assert.equal(accessoryPath({id:'pearl-belt'}),'/accessories/pearl-belt');
assert.equal(accessoryCollectionPath({id:'evening-edit'}),'/accessories/collections/evening-edit');
assert.equal(accessoryCategoryPath({id:'jewellery'}),'/accessories/category/jewellery');
const products=[{id:'SH-ONE',title:'One',accessories:[{name:'Existing Scarf',image:'assets/scarf.png',visible:true}]}];
const accessories=[{id:'a',name:'Pearl Belt',image:'assets/belt.png',price:'2500',relatedLookIds:['SH-ONE'],collectionIds:['evening-edit'],sortOrder:3,visible:true},
{id:'b',name:'Hidden',image:'assets/hidden.png',visible:false,relatedLookIds:['SH-ONE'],sortOrder:0}];
assert.equal(visibleAccessories(accessories).length,1);
assert.ok(accessoryMatchesCollection(accessories[0],'evening-edit'));
assert.ok(!accessoryMatchesCollection(accessories[0],'other'));
const updated=decorateLookAccessories(products,accessories);
assert.equal(products[0].accessories.length,1,'decorating a public look does not change saved product data');
assert.equal(updated[0].accessories.length,2);
assert.equal(updated[0].accessories[1].publicPath,'/accessories/a');
assert.equal(legacyAccessories(products,accessories).length,1,'older look accessories stay visible on catalogue landing');
const duplicated=[...accessories,{id:'c',name:'Existing Scarf',image:'assets/scarf.png',visible:true}];
assert.equal(legacyAccessories(products,duplicated).length,0,'same photo/name does not display twice');
for(const file of ['app/accessories/[accessorySlug]/page.js','app/accessories/collections/[collectionSlug]/page.js','app/accessories/category/[categorySlug]/page.js'])assert.ok(fs.existsSync(path.join(root,file)),'missing public route '+file);
const server=read('lib/cms-server-api.js');
for(const key of ['cms_accessories','cms_accessory_categories','cleanAccessory','cleanAccessoryCategory','relatedLookIds','accessoryIds'])assert.ok(server.includes(key),'missing server support '+key);
const cms=read('components/admin/CmsApp.jsx');
for(const label of ['Accessory Categories','+ New Accessory','+ Clothing Collection','+ Accessory Collection','Include in Accessory Collections','Style With Clothing Looks','Featured Clothing Collections'])assert.ok(cms.includes(label),'missing CMS control '+label);
const catalogue=read('lib/catalogue-render.mjs');
for(const value of ['v1193-collection-cards','v1193-category-links','v1193-accessory-card','ENQUIRE ABOUT THIS ACCESSORY'])assert.ok(catalogue.includes(value),'missing public display '+value);
const final=read('lib/final-feedback-v119.mjs');
assert.ok(!final.includes("$('.cms-curated-showcase .cms-curated-name strong').each"),'collection names must not be replaced by COLLECTION');
const publicData=read('lib/cms-data.js');
assert.ok(publicData.includes('loadAccessories')&&publicData.includes('loadAccessoryCategories'));
assert.match(read('firestore.rules'),/match \/cms_accessories\/\{id\} \{ allow read: if true; allow write: if false; \}/);
assert.match(read('firestore.rules'),/match \/cms_accessory_categories\/\{id\} \{ allow read: if true; allow write: if false; \}/);
assert.match(read('public/shaneryn-catalogue-v1193.css'),/height:auto!important/);
const typescript=await import('typescript').catch(()=>null);
if(typescript){const ts=typescript.default||typescript;
 const file='components/admin/CmsApp.jsx',result=ts.transpileModule(read(file),{fileName:file,reportDiagnostics:true,compilerOptions:{jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2022}});
 assert.equal(result.diagnostics.length,0,'admin JSX should parse');}
console.log('PASS v1.19.3: independent catalogues, hidden starter collections, multi-collection membership, safe legacy coexistence, CMS controls, public routes and image sizing.');
