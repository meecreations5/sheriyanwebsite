assert.equal(migrated.custom.value,'Keep custom text');
assert.equal(legacy.f00235.value,'MADE FOR THE MOMENT','Do not mutate existing saved documents');
assert.equal(upgradeLookEditorialPatches('index',legacy),legacy);
assert.equal(upgradeLookEditorialPatches('look',{f00236:{value:'Custom designer text'}}).f00236.value,'Custom designer text');
console.log('PASS V1.18.9: three-line closing styling, measurement submission, inches only, item hierarchy and CMS compatibility');
