import assert from 'node:assert/strict';
import {upgradeLookEditorialPatches} from '../lib/look-editorial-defaults.mjs';
import {read} from './look-info-mock.mjs';
const seed=JSON.parse(read('data/seed/pages/look.json'));
const html=seed.bodyHtml,css=read('public/look-detail-v45.css'),js=read('public/look-detail-v45.js'),render=read('lib/render-page.js');
const expected=['clothes to empower','effortless moments','for fun celebrations'];
for(const value of expected)assert.ok(html.includes(value),value);
assert.match(html,/<span class="ep-kicker ld-interlude-kicker"/);
assert.match(html,/<h2 class="ld-interlude-headline"/);
assert.match(html,/<p class="ld-interlude-note"/);
assert.match(css,/\.ld-interlude-kicker\{[^}]*color:#e4a9c9!important/);
assert.match(css,/\.ld-interlude h2\.ld-interlude-headline\{color:#fff/);
assert.match(css,/\.ld-interlude p\.ld-interlude-note\{color:#fff/);
assert.doesNotMatch(html,/MADE FOR THE MOMENT|Clothing that lives|Considered silhouettes\. Personal expression\. Your own way/);
for(const id of ['f00235','f00236','f00238'])assert.ok(seed.fields.some(f=>f.id===id),'CMS field '+id+' missing');
assert.ok(!seed.fields.some(f=>f.id==='f00237'),'Obsolete italic headline field must not appear');
assert.ok(html.includes('MEASUREMENTS REQUIRED'));
assert.ok(html.includes('SUBMIT YOUR MEASUREMENTS'));
assert.ok(html.includes('ld-customer-name')&&html.includes('ld-customer-email'));
assert.doesNotMatch(html,/Centimetres|Centimeters|MADE TO MEASURE|Considered around you|Nothing is submitted or stored on this prototype/);
assert.match(js,/fetch\('\/api\/requests'/);
assert.match(js,/measurementSummary:values\.join/);
assert.match(js,/source:location\.pathname/);
assert.match(js,/kind:'enquiry'/);
assert.match(js,/colourDot\)colourDot\.style/);
assert.match(read('public/editorial-pages.js'),/const tone=\$\('#detail-tone'\);if\(tone\)/);
assert.match(render,/\.ld-colour'\)\.remove\(\)/);
assert.match(render,/\.ld-accordions'\)\.remove\(\)/);
assert.match(css,/\.ld-product-price strong\{font:500 clamp\(22px/);
assert.match(css,/\.ld-look-category/);
assert.match(read('lib/cms-data.js'),/upgradeLookEditorialPatches/);
assert.match(read('lib/cms-server-api.js'),/upgradeLookEditorialPatches/);
const legacy={f00235:{value:'MADE FOR THE MOMENT',visible:true},f00236:{value:'Clothing that lives ',visible:true},f00238:{value:'Considered silhouettes. Personal expression. Your own way of being.',visible:true},custom:{value:'Keep custom text'}};
