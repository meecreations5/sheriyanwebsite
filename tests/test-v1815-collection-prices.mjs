import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read = file => fs.readFileSync(path.join(root,file),'utf8');
const source=read('public/site.js');
const editorial=read('public/editorial-pages.js');
const css=read('public/shaneryn-v1815-collection-prices.css');
const page=read('components/LegacyPage.jsx');
const data=read('lib/cms-data.js');
const getLine=(text,prefix)=>{const line=text.split('\n').find(s=>s.includes(prefix));assert.ok(line,prefix);return line.trim();};
const helpers=getLine(source,'const escapeText =')+'\n'+getLine(source,'const priceLabel =');
const context={};
vm.runInNewContext(helpers+'\nthis.escapeText=escapeText;this.priceLabel=priceLabel;',context);
assert.equal(context.priceLabel('17000'),'₹17,000');
assert.equal(context.priceLabel('17,000'),'₹17,000');
assert.equal(context.priceLabel('₹ 17,000'),'₹ 17,000');
assert.equal(context.priceLabel('AED 950'), 'AED 950');
assert.equal(context.priceLabel('  '),'');
assert.equal(context.escapeText('<img src=x onerror=alert(1)>'),'&lt;img src=x onerror=alert(1)&gt;');
const lookGrid={innerHTML:''},lookCount={textContent:''},categoryView={hidden:false};
const product={id:'SH-STARLIGHT',title:'Starlight',cat:'Skirt Sets',img:'/assets/look.webp',publicPath:'/look/starlight',price:'17,000'};
const runtime={...context,A:'',activeCategory:'All',lookData:[product],getFiltered:()=>[product],getSaved:()=>[],all:()=>[],find:q=>({'#look-grid':lookGrid,'#look-count':lookCount,'#category-view-link':categoryView}[q]||null)};
const start=source.indexOf('  function renderLooks(){');
const end=source.indexOf('  function showLook(',start);
assert.ok(start>=0 && end>start,'Listing renderer exists');
vm.runInNewContext(source.slice(start,end)+'\nrenderLooks();',runtime);
assert.match(lookGrid.innerHTML, /class="catalogue-price">₹17,000<\/p>/);
assert.match(lookGrid.innerHTML, /\/look\/starlight/);
assert.equal(lookCount.textContent,'1 look');
product.price='';
vm.runInNewContext(source.slice(start,end)+'\nrenderLooks();',runtime);
assert.doesNotMatch(lookGrid.innerHTML, /class="catalogue-price"/);
product.price='<script>alert(1)</script>';
vm.runInNewContext(source.slice(start,end)+'\nrenderLooks();',runtime);
assert.match(lookGrid.innerHTML, /&lt;script&gt;alert\(1\)&lt;\/script&gt;/);
const editorHelpers=getLine(editorial,'const escapeText =')+'\n'+getLine(editorial,'const priceLabel =');
const cardLine=getLine(editorial,'const card =');
const eCtx={assetSrc:v=>v};
vm.runInNewContext(editorHelpers+'\n'+cardLine+'\nthis.card=card;',eCtx);
product.price='₹17,000';
assert.match(eCtx.card(product,true),/class="ep-card-price">₹17,000<\/p>/);
assert.doesNotMatch(eCtx.card(product,false),/class="ep-card-price"/);
assert.match(editorial,/group\.map\(p=>card\(p,true\)\)/);
assert.ok(page.includes("['collections','collection'].includes(slug)"),'Both catalogue routes include style override');
assert.match(css,/catalogue-price/);
assert.match(css,/ep-card-price/);
assert.match(data,/const baseline=seedProducts\(\)/);
assert.match(data,/\.\.\.p\}/); // DB product price passes through unchanged
console.log('PASS: published collection grids show prices; empty price hidden; formatted INR and existing currencies retained; HTML escaped');
